#!/usr/bin/env python3
"""Refresh the single audited-source manifest after reviewing runtime source edits."""
from hashlib import sha256
from pathlib import Path

root = Path(__file__).resolve().parents[2]
std = root / "src/Vibranium.Std"
paths = sorted(path for path in std.rglob("*.cs") if not {"bin", "obj"}.intersection(path.relative_to(std).parts))
paths.append(root / "src/Vibranium.Core/Bootstrap/VibraniumAppBootstrap.cs")
entries = []
for path in paths:
    key = path.relative_to(root / "src").as_posix()
    digest = sha256(path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").encode("utf-8")).hexdigest().upper()
    entries.append(f'        ["{key}"] = "{digest}",')
output = """// Generated by GenerateTrustedSourceHashes.py. Do not edit hashes by hand.
using System.Collections.Generic;

namespace Vibranium.Frontend.Roslyn;

internal static partial class TrustedRuntimeSources
{
    private static readonly IReadOnlyDictionary<string, string> SourceHashes = new Dictionary<string, string>
    {
""" + "\n".join(entries) + "\n    };\n}\n"
Path(__file__).with_name("TrustedRuntimeSources.Hashes.cs").write_text(output, encoding="utf-8")
