namespace Vibranium.Mutation;

internal sealed record SdkResult(CSharpCompilation Compilation, CsError[] Errors);

internal sealed class Oracles
{
    /// <summary>
    /// Stage0's own zero-safety predicate (<c>VibraniumSymbolHelpers.IsZeroSafeTypeSymbol</c>, internal to the Roslyn
    /// frontend). The CS0649 triage key follows Stage0's rejection set exactly, so the tool calls that predicate instead of
    /// copying it. Binding fails at start-up if the frontend renames it.
    /// </summary>
    private static readonly Func<ITypeSymbol?, CSharpCompilation?, HashSet<ITypeSymbol>?, bool> s_isZeroSafe =
        (typeof(VibraniumFrontend).Assembly.GetType("Vibranium.Frontend.Roslyn.VibraniumSymbolHelpers", throwOnError: true)!
            .GetMethod("IsZeroSafeTypeSymbol", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)
            ?? throw new MissingMethodException("VibraniumSymbolHelpers.IsZeroSafeTypeSymbol"))
        .CreateDelegate<Func<ITypeSymbol?, CSharpCompilation?, HashSet<ITypeSymbol>?, bool>>();

    /// <summary>CS0649 points at the field's declarator: is that field's type zero-safe, as Stage0 decides?</summary>
    private static bool UnassignedFieldIsZeroSafe(CSharpCompilation compilation, Diagnostic diagnostic)
    {
        if (diagnostic.Location.SourceTree is not { } tree) return false;
        var declarator = tree.GetRoot().FindNode(diagnostic.Location.SourceSpan)
            .FirstAncestorOrSelf<Microsoft.CodeAnalysis.CSharp.Syntax.VariableDeclaratorSyntax>();
        return declarator is not null
            && compilation.GetSemanticModel(tree).GetDeclaredSymbol(declarator) is IFieldSymbol field
            && s_isZeroSafe(field.Type, compilation, null);
    }

    private readonly string _root;
    private readonly string _self;
    private readonly int _timeout;
    private readonly ImmutableArray<MetadataReference> _references;
    private readonly SyntaxTree[] _support;
    private readonly CSharpCompilationOptions _options;
    private readonly HashSet<string> _explicitPromotions;
    private static readonly Regex IdPattern = new(@"^(?:.*\(\d+,\d+\)|vib): error (?<id>VIB\d{3}):", RegexOptions.CultureInvariant | RegexOptions.Multiline);

    public Oracles(string root, string self, string vibraniumReferences, string referencePack, int timeout)
    {
        _root = root;
        _self = self;
        _timeout = timeout;
        ReferencePack = referencePack;
        VibraniumReferences = vibraniumReferences;
        _references = [.. Directory.GetFiles(referencePack, "*.dll").Order(StringComparer.Ordinal)
            .Append(Path.Combine(vibraniumReferences, "Vibranium.Core.dll"))
            .Append(Path.Combine(vibraniumReferences, "Vibranium.Std.dll"))
            .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))];
        _support =
        [
            CSharpSyntaxTree.ParseText("// <auto-generated/>\nglobal using global::System;\nglobal using global::Vibranium;\nglobal using global::Vibranium.Std;\nglobal using static global::Vibranium.Prelude;\nglobal using static global::Vibranium.Std.ConsoleIo;\n", Corpus.ParseOptions, "obj/App.GlobalUsings.g.cs"),
            // The physical path, as MSBuild passes it (App.props' obj/ Link is display metadata only): the analyzer trusts
            // this audited runtime source by path suffix and digest, and a synthetic obj/ path made it report VIB000.
            CSharpSyntaxTree.ParseText(File.ReadAllText(BootstrapPath(root)), Corpus.ParseOptions, BootstrapPath(root)),
        ];
        string props = File.ReadAllText(Path.Combine(root, "Vibranium.App.props"));
        var promoted = Regex.Matches(props, @"<WarningsAsErrors>([^<]*)</WarningsAsErrors>")
            .SelectMany(m => m.Groups[1].Value.Split(';', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            .Where(id => id.StartsWith("CS", StringComparison.Ordinal)).Distinct()
            .ToDictionary(id => id, _ => ReportDiagnostic.Error, StringComparer.Ordinal);
        _explicitPromotions = new HashSet<string>(promoted.Keys, StringComparer.Ordinal);
        promoted["CS1701"] = ReportDiagnostic.Suppress;
        promoted["CS1702"] = ReportDiagnostic.Suppress;
        _options = new CSharpCompilationOptions(OutputKind.ConsoleApplication,
            nullableContextOptions: NullableContextOptions.Enable, checkOverflow: false, allowUnsafe: false,
            optimizationLevel: OptimizationLevel.Debug, warningLevel: 11, deterministic: true,
            generalDiagnosticOption: ReportDiagnostic.Error, specificDiagnosticOptions: promoted);
    }

    private static string BootstrapPath(string root) => Path.GetFullPath(Path.Combine(root, "src", "Vibranium.Core", "Bootstrap", "VibraniumAppBootstrap.cs"));

    public SdkResult Sdk(string source)
    {
        var tree = CSharpSyntaxTree.ParseText(source, Corpus.ParseOptions, "Program.cs");
        var compilation = CSharpCompilation.Create("Program", _support.Append(tree), _references, _options);
        // Preserve Roslyn's deterministic diagnostic order: this is the first SDK CS error,
        // not an arbitrary preferred ID selected to manufacture a bucket.
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error && d.Id.StartsWith("CS", StringComparison.Ordinal))
            .Select(d =>
            {
                var location = d.Location.GetLineSpan().StartLinePosition;
                string promotion = !d.IsWarningAsError ? "error" : _explicitPromotions.Contains(d.Id) ? "explicit" : "blanket";
                return new CsError(d.Id, d.Location.SourceSpan.Start, location.Line + 1, location.Character + 1,
                    d.GetMessage(CultureInfo.InvariantCulture), d.IsWarningAsError, promotion,
                    d.Id == "CS0649" ? UnassignedFieldIsZeroSafe(compilation, d) : null);
            }).ToArray();
        return new SdkResult(compilation, errors);
    }

    public static FrontendResult Analyzer(SdkResult sdk)
    {
        try
        {
            string? failure = null;
            var withAnalyzers = new CompilationWithAnalyzers(sdk.Compilation, [new VibraniumDiagnosticAnalyzer()],
                new CompilationWithAnalyzersOptions(new AnalyzerOptions([]),
                    (ex, _, _) => failure = ex.GetType().Name, concurrentAnalysis: false, logAnalyzerExecutionTime: false));
            var diagnostics = withAnalyzers.GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
            string[] ids = diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => d.Id).Distinct().Order(StringComparer.Ordinal).ToArray();
            if (failure is not null || ids.Contains("AD0001")) return new FrontendResult("crash", ids, -1, failure ?? "AD0001");
            // The Analyzer frontend is the SDK + analyzer, not the analyzer DLL stripped of its compiler.
            return new FrontendResult(sdk.Errors.Length > 0 || ids.Length > 0 ? "reject" : "accept", ids,
                sdk.Errors.Length > 0 || ids.Length > 0 ? 1 : 0);
        }
        catch (Exception ex)
        {
            return new FrontendResult("crash", [], -1, ex.GetType().Name);
        }
    }

    public FrontendResult Stage0(string path)
    {
        try
        {
            var compilation = VibraniumCompilerDriver.CreateCompilationFromPath(path, includeStd: true, sysroot: Path.Combine(_root, "src"));
            if (VibraniumFrontend.HasDeclarationCuts(compilation))
            {
                string[] cuts = VibraniumFrontend.CompileAndCheck(compilation).Diagnostics.Select(d => d.Id).Distinct().Order(StringComparer.Ordinal).ToArray();
                return new FrontendResult(cuts.Length > 0 ? "reject" : "accept", cuts, cuts.Length > 0 ? 1 : 0);
            }
            string[] cs = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error || d.IsWarningAsError)
                .Select(d => d.Id).Distinct().Order(StringComparer.Ordinal).ToArray();
            if (cs.Length > 0) return new FrontendResult("reject", cs, 1);
            string[] ids = VibraniumFrontend.CompileAndCheck(compilation).Diagnostics.Select(d => d.Id).Distinct().Order(StringComparer.Ordinal).ToArray();
            return new FrontendResult(ids.Length > 0 ? "reject" : "accept", ids, ids.Length > 0 ? 1 : 0);
        }
        catch (Exception ex)
        {
            return new FrontendResult("crash", [], -1, ex.GetType().Name);
        }
    }

    public string SelfDll => _self;

    /// <summary>The directory whose Vibranium.Core.dll and Vibranium.Std.dll the SDK oracle compiles against.</summary>
    public string VibraniumReferences { get; }

    /// <summary>
    /// Every vib-self process gets a managed-heap hard limit, so an input that sends self into unbounded
    /// allocation (a struct that contains itself) ends as a failure instead of exhausting the machine.
    /// </summary>
    public IReadOnlyDictionary<string, string> SelfEnvironment { get; init; } = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["DOTNET_GCHeapHardLimit"] = "0x40000000",
    };

    public string ReferencePack { get; }

    /// <summary>Address-space limit, in MiB, for a native self (no GC heap limit applies there).</summary>
    public int SelfNativeAddressSpaceMb { get; init; } = 4096;

    /// <summary>True when the self compiler is a native executable (for example bootstrap's vib-stage2), not a .dll.</summary>
    public bool SelfIsNative => !_self.EndsWith(".dll", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// <c>check</c> only: self is never asked to build or run C#-invalid input. A managed self runs under dotnet with the
    /// heap limit in <see cref="SelfEnvironment"/>. A native self runs directly, and through prlimit under an
    /// address-space limit when prlimit is available.
    /// </summary>
    public FrontendResult Self(string path)
    {
        string[] check = ["check", path, "--sysroot", Path.Combine(_root, "src")];
        var run = !SelfIsNative
            ? RunProcess("dotnet", [_self, .. check], _root, _timeout, SelfEnvironment)
            : s_prlimit is { } prlimit
                ? RunProcess(prlimit, ["--as=" + ((long)SelfNativeAddressSpaceMb * 1024 * 1024).ToString(CultureInfo.InvariantCulture), "--", _self, .. check], _root, _timeout)
                : RunProcess(_self, check, _root, _timeout);
        return run.TimedOut ? new FrontendResult("timeout", [], -1) : ParseSelfResult(run.ExitCode, run.Output);
    }

    private static readonly string? s_prlimit = new[] { "/usr/bin/prlimit", "/bin/prlimit" }.FirstOrDefault(File.Exists);

    public sealed record ProcessRun(int ExitCode, string Output, bool TimedOut, double Seconds);

    /// <summary>Runs a process with stdin closed, collecting stdout+stderr; kills the whole tree on timeout.</summary>
    public static ProcessRun RunProcess(string file, IEnumerable<string> arguments, string workingDirectory, int timeout,
        IReadOnlyDictionary<string, string>? environment = null)
    {
        var start = new ProcessStartInfo(file)
        {
            RedirectStandardOutput = true, RedirectStandardError = true, RedirectStandardInput = true,
            UseShellExecute = false, WorkingDirectory = workingDirectory,
        };
        foreach (string arg in arguments) start.ArgumentList.Add(arg);
        start.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        start.Environment["DOTNET_TieredPGO"] = "0";
        if (environment is not null)
            foreach (var pair in environment) start.Environment[pair.Key] = pair.Value;
        var clock = Stopwatch.StartNew();
        using var process = Process.Start(start) ?? throw new InvalidOperationException("Could not start " + file);
        process.StandardInput.Close();
        var output = process.StandardOutput.ReadToEndAsync();
        var error = process.StandardError.ReadToEndAsync();
        if (!process.WaitForExit(timeout))
        {
            process.Kill(entireProcessTree: true);
            process.WaitForExit();
            return new ProcessRun(-1, Truncate(output.GetAwaiter().GetResult() + error.GetAwaiter().GetResult()), true, clock.Elapsed.TotalSeconds);
        }
        process.WaitForExit();
        return new ProcessRun(process.ExitCode, Truncate(output.GetAwaiter().GetResult() + error.GetAwaiter().GetResult()), false, clock.Elapsed.TotalSeconds);
    }

    private static string Truncate(string text) => text.Length <= 200_000 ? text : text[..100_000] + "\n[...]\n" + text[^100_000..];

    public static FrontendResult ParseSelfResult(int exitCode, string text)
    {
        string[] ids = IdPattern.Matches(text).Select(m => m.Groups["id"].Value)
            .Distinct().Order(StringComparer.Ordinal).ToArray();
        string status = exitCode == 0 && ids.Length == 0 ? "accept" : exitCode == 1 && ids.Length > 0 ? "reject" : "failure";
        return new FrontendResult(status, ids, exitCode,
            status == "failure" ? "Unexpected exit code, missing check diagnostic, or inconsistent success status." : null);
    }

    public static string FindReferencePack()
    {
        string? runtime = Path.GetDirectoryName(typeof(object).Assembly.Location);
        string dotnet = Path.GetFullPath(Path.Combine(runtime!, "../../.."));
        string packs = Path.Combine(dotnet, "packs/Microsoft.NETCore.App.Ref");
        return Directory.EnumerateDirectories(packs).Where(p => Path.GetFileName(p).StartsWith("11.", StringComparison.Ordinal))
            .OrderByDescending(p => Version.Parse(Path.GetFileName(p).Split('-')[0])).Select(p => Path.Combine(p, "ref/net11.0"))
            .First(Directory.Exists);
    }
}
