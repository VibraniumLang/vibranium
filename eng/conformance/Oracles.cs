/// <summary>Locations of the pinned toolchain and the built compilers.</summary>
internal sealed record Toolchain(string RepoRoot, string SelfDir, string RefPackDir, string Clang, string ReadElf)
{
    public string Sysroot => Path.Combine(RepoRoot, "src");
    public string Bootstrap => Path.Combine(RepoRoot, "src", "Vibranium.Core", "Bootstrap", "VibraniumAppBootstrap.cs");
    public string CoreDll => Path.Combine(SelfDir, "Vibranium.Core.dll");
    public string StdDll => Path.Combine(SelfDir, "Vibranium.Std.dll");
    public string SelfDll => Path.Combine(SelfDir, "vib-self.dll");
}

internal sealed record DiagLine(string Id, int Line, int Col, string Message)
{
    public override string ToString() => $"{Id}@{Line}:{Col} {Message}";
}

/// <summary>Oracle 1: Roslyn compilation emulating an SDK build with Vibranium.App.props, plus the real Analyzer.</summary>
internal sealed class SdkOracle
{
    private readonly ImmutableArray<MetadataReference> _refs;
    private readonly SyntaxTree _globalUsings;
    private readonly SyntaxTree _bootstrap;
    private readonly CSharpParseOptions _parse;
    private readonly CSharpCompilationOptions _options;

    public SdkOracle(Toolchain tc)
    {
        var refs = Directory.EnumerateFiles(tc.RefPackDir, "*.dll").OrderBy(f => f, StringComparer.Ordinal)
            .Select(f => (MetadataReference)MetadataReference.CreateFromFile(f)).ToList();
        refs.Add(MetadataReference.CreateFromFile(tc.CoreDll));
        refs.Add(MetadataReference.CreateFromFile(tc.StdDll));
        _refs = [.. refs];
        _parse = new CSharpParseOptions(LanguageVersion.CSharp15, preprocessorSymbols: ["TRACE", "DEBUG", "NET", "NET11_0", "NETCOREAPP", "NET11_0_OR_GREATER", "NET5_0_OR_GREATER", "NETCOREAPP3_0_OR_GREATER"]);
        _globalUsings = CSharpSyntaxTree.ParseText("""
            // <auto-generated/>
            global using global::System;
            global using global::Vibranium;
            global using global::Vibranium.Std;
            global using static global::Vibranium.Prelude;
            global using static global::Vibranium.Std.ConsoleIo;
            """, _parse, path: "obj/Program.GlobalUsings.g.cs");
        // the real source path, as csc gets it from Vibranium.App.props (the Link metadata only renames it in the IDE); the
        // Analyzer authenticates the bootstrap by path and content hash (TrustedRuntimeSources, from the A-F3 fix on)
        _bootstrap = CSharpSyntaxTree.ParseText(File.ReadAllText(tc.Bootstrap), _parse, path: tc.Bootstrap);
        _options = new CSharpCompilationOptions(
            OutputKind.ConsoleApplication,
            nullableContextOptions: NullableContextOptions.Enable,
            checkOverflow: false,
            allowUnsafe: false,
            optimizationLevel: OptimizationLevel.Debug,
            warningLevel: 11,
            deterministic: true,
            specificDiagnosticOptions: new Dictionary<string, ReportDiagnostic>
            {
                ["CS1701"] = ReportDiagnostic.Suppress,
                ["CS1702"] = ReportDiagnostic.Suppress,
            }.Concat(PromotedWarnings(tc).Select(id => KeyValuePair.Create(id, ReportDiagnostic.Error))).ToDictionary());
    }

    /// <summary>The CS IDs the target tree's Vibranium.App.props promotes with &lt;WarningsAsErrors&gt;.</summary>
    public static IReadOnlyList<string> PromotedWarnings(Toolchain tc)
    {
        string props = File.ReadAllText(Path.Combine(tc.RepoRoot, "Vibranium.App.props"));
        return [.. Regex.Matches(props, @"<WarningsAsErrors>([^<]*)</WarningsAsErrors>")
            .SelectMany(m => m.Groups[1].Value.Split(';', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            .Where(x => x.StartsWith("CS", StringComparison.Ordinal))
            .Distinct()
            .Order(StringComparer.Ordinal)];
    }

    public sealed record Result(CSharpCompilation Compilation, List<DiagLine> Errors, List<DiagLine> Warnings, List<DiagLine> Analyzer, string? AnalyzerCrash);

    public Result Check(string source, string path)
    {
        var tree = CSharpSyntaxTree.ParseText(source, _parse, path: path);
        var comp = CSharpCompilation.Create("Program", [_globalUsings, tree, _bootstrap], _refs, _options);
        var diags = comp.GetDiagnostics();
        var errors = new List<DiagLine>();
        var warnings = new List<DiagLine>();
        foreach (var d in diags)
        {
            if (d.Severity == DiagnosticSeverity.Error)
            {
                errors.Add(Line(d));
            }
            else if (d.Severity == DiagnosticSeverity.Warning)
            {
                warnings.Add(Line(d));
            }
        }
        string? crash = null;
        var analyzer = new List<DiagLine>();
        var cwa = new CompilationWithAnalyzers(comp, [new VibraniumDiagnosticAnalyzer()], new CompilationWithAnalyzersOptions(
            new AnalyzerOptions([]), (ex, _, _) => crash = ex.GetType().Name + ": " + ex.Message, concurrentAnalysis: false, logAnalyzerExecutionTime: false));
        foreach (var d in cwa.GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult())
        {
            analyzer.Add(Line(d));
        }
        return new Result(comp, errors, warnings, analyzer, crash);
    }

    private static DiagLine Line(Diagnostic d)
    {
        var p = d.Location.GetLineSpan().StartLinePosition;
        return new DiagLine(d.Id, p.Line + 1, p.Character + 1, d.GetMessage(System.Globalization.CultureInfo.InvariantCulture));
    }

    /// <summary>Emits the managed program (only for error-free compilations).</summary>
    public static string? Emit(CSharpCompilation comp, string dllPath)
    {
        using var fs = File.Create(dllPath);
        var r = comp.Emit(fs);
        return r.Success ? null : string.Join("; ", r.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => d.Id));
    }
}

/// <summary>Oracle 2: Stage-0 `vib check` path (driver + Roslyn errors + VibraniumFrontend), in process.</summary>
internal sealed class Stage0Oracle(Toolchain tc)
{
    public sealed record Result(bool Accepted, List<DiagLine> Diags, string? Crash, Compiler.Core.MirModule? Module);

    private static readonly Regex DiagRx = new(@"\((\d+),(\d+)\): (?:error|warning) ([A-Z]+\d+): (.*)$", RegexOptions.Compiled);

    public Result Check(string path)
    {
        try
        {
            var comp = VibraniumCompilerDriver.CreateCompilationFromPaths([path], includeStd: true, sysroot: tc.Sysroot);
            var cs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error || d.IsWarningAsError).ToList();
            if (cs.Count > 0)
            {
                return new Result(false, [.. cs.Select(d =>
                {
                    var p = d.Location.GetLineSpan().StartLinePosition;
                    return new DiagLine(d.Id, p.Line + 1, p.Character + 1, d.GetMessage(System.Globalization.CultureInfo.InvariantCulture));
                })], null, null);
            }
            var res = VibraniumFrontend.CompileAndCheck(comp);
            if (res.Diagnostics.Count > 0)
            {
                return new Result(false, [.. res.Diagnostics.Select(d => new DiagLine(d.Id, d.Span.Line, d.Span.Column, d.Message))], null, null);
            }
            return new Result(true, [], null, res.Module);
        }
        catch (Exception ex)
        {
            return new Result(false, [], ex.GetType().Name + ": " + ex.Message, null);
        }
    }

    /// <summary>The `vib emit-ll` text of an accepted module (no clang, nothing run), for the static IR contract.</summary>
    public string? EmitIr(Compiler.Core.MirModule module)
    {
        try
        {
            return Llvm18Backend.EmitModuleIr(module, new LlvmEmitOptions(AddressSanitizer: false));
        }
        catch (Exception ex)
        {
            return "; emit failed: " + ex.GetType().Name;
        }
    }

    /// <summary>`vib build` back end: IR emission + the exact Llvm18Backend clang invocation.</summary>
    public (bool Ok, string Log) Build(Compiler.Core.MirModule module, string binPath, int opt, bool asan)
    {
        try
        {
            string ir = Llvm18Backend.EmitModuleIr(module, new LlvmEmitOptions(AddressSanitizer: asan));
            var (exit, output) = Llvm18Backend.CompileToExecutable(ir, binPath, opt, asan, tc.Clang);
            return (exit == 0, output);
        }
        catch (Exception ex)
        {
            return (false, "exception " + ex.GetType().Name + ": " + ex.Message);
        }
    }

    public static List<DiagLine> ParseCliLines(string text)
    {
        var res = new List<DiagLine>();
        foreach (var raw in text.Split('\n'))
        {
            var m = DiagRx.Match(raw.TrimEnd());
            if (m.Success)
            {
                res.Add(new DiagLine(m.Groups[3].Value, int.Parse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture), int.Parse(m.Groups[2].Value, System.Globalization.CultureInfo.InvariantCulture), m.Groups[4].Value));
            }
        }
        return res;
    }
}

internal sealed record ProcResult(int Exit, string Stdout, string Stderr, bool TimedOut, long Ms)
{
    public string Short => TimedOut ? "TIMEOUT" : $"exit={Exit} out=[{Esc(Stdout)}] err=[{Esc(Stderr)}]";

    private static string Esc(string s)
    {
        s = s.Replace("\n", "|", StringComparison.Ordinal);
        return s.Length > 600 ? s[..600] + "..." : s;
    }
}

internal static class Proc
{
    public static ProcResult Run(string file, IEnumerable<string> args, int timeoutMs, string? cwd = null)
    {
        var psi = new ProcessStartInfo(file)
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            RedirectStandardInput = true,
            UseShellExecute = false,
            WorkingDirectory = cwd ?? Environment.CurrentDirectory,
        };
        foreach (var a in args)
        {
            psi.ArgumentList.Add(a);
        }
        psi.Environment["ASAN_OPTIONS"] = "detect_leaks=1";
        psi.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        psi.Environment["DOTNET_TieredPGO"] = "0";
        var sw = Stopwatch.StartNew();
        using var p = Process.Start(psi) ?? throw new InvalidOperationException("cannot start " + file);
        p.StandardInput.Close();
        var so = p.StandardOutput.ReadToEndAsync();
        var se = p.StandardError.ReadToEndAsync();
        if (!p.WaitForExit(timeoutMs))
        {
            try
            {
                p.Kill(entireProcessTree: true);
            }
            catch (InvalidOperationException)
            {
            }
            p.WaitForExit();
            return new ProcResult(-1, so.Result, se.Result, true, sw.ElapsedMilliseconds);
        }
        p.WaitForExit();
        return new ProcResult(p.ExitCode, so.Result, se.Result, false, sw.ElapsedMilliseconds);
    }
}

/// <summary>In-memory sink installed as the self compiler's Stdio streams.</summary>
internal sealed class CaptureStream : Stream
{
    private readonly MemoryStream _ms = new();

    public override bool CanRead => false;
    public override bool CanSeek => false;
    public override bool CanWrite => true;
    public override long Length => _ms.Length;

    public override long Position
    {
        get => _ms.Position;
        set => throw new NotSupportedException();
    }

    public override void Flush()
    {
    }

    public override int Read(byte[] buffer, int offset, int count) => throw new NotSupportedException();

    public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();

    public override void SetLength(long value) => throw new NotSupportedException();

    public override void Write(byte[] buffer, int offset, int count) => _ms.Write(buffer, offset, count);

    public override void Write(ReadOnlySpan<byte> buffer) => _ms.Write(buffer);

    public string Take()
    {
        string s = Encoding.UTF8.GetString(_ms.GetBuffer(), 0, (int)_ms.Length);
        _ms.SetLength(0);
        return s;
    }
}

/// <summary>
/// Oracle 3 in process: the real vib-self entry point loaded into its own AssemblyLoadContext, so
/// its Vibranium.Core/Std copies (and their statics) are private to one worker. Arguments go
/// through Std's cached argument table; Core's Stdio streams are replaced by in-memory sinks before
/// any Stdio method is compiled; panics surface as exceptions (InProcessTestMode) and are mapped to
/// exit 101 + `panic: msg` exactly like the process-mode unhandled-exception hook.
/// </summary>
internal sealed class SelfHost
{
    private readonly MethodInfo _entry;
    private readonly FieldInfo _argBytes;
    private readonly Type _panicType;
    private readonly CaptureStream _out = new();
    private readonly CaptureStream _err = new();

    private sealed class SelfAlc(string dir) : AssemblyLoadContext("vib-self", isCollectible: false)
    {
        protected override Assembly? Load(AssemblyName name)
        {
            string p = Path.Combine(dir, name.Name + ".dll");
            return File.Exists(p) ? LoadFromAssemblyPath(p) : null;
        }
    }

    public SelfHost(Toolchain tc)
    {
        var alc = new SelfAlc(tc.SelfDir);
        var asm = alc.LoadFromAssemblyPath(tc.SelfDll);
        var core = alc.LoadFromAssemblyName(new AssemblyName("Vibranium.Core"));
        var std = alc.LoadFromAssemblyName(new AssemblyName("Vibranium.Std"));
        if (ReferenceEquals(core, typeof(Vibranium.Option<>).Assembly))
        {
            throw new InvalidOperationException("vib-self Core was not isolated");
        }
        _entry = asm.EntryPoint ?? throw new InvalidOperationException("vib-self has no entry point");
        _argBytes = std.GetType("Vibranium.Std.Sys", throwOnError: true)!.GetField("s_argBytes", BindingFlags.NonPublic | BindingFlags.Static)
            ?? throw new InvalidOperationException("Sys.s_argBytes not found");
        var runtime = core.GetType("Vibranium.VibraniumRuntime", throwOnError: true)!;
        runtime.GetProperty("InProcessTestMode")!.SetValue(null, true);
        _panicType = core.GetType("Vibranium.VibraniumPanicException", throwOnError: true)!;
        var stdio = core.GetType("Vibranium.Stdio", throwOnError: true)!;
        RuntimeHelpers.RunClassConstructor(stdio.TypeHandle);
        SetStatic(stdio.GetField("s_out", BindingFlags.NonPublic | BindingFlags.Static) ?? throw new InvalidOperationException("Stdio.s_out not found"), _out);
        SetStatic(stdio.GetField("s_err", BindingFlags.NonPublic | BindingFlags.Static) ?? throw new InvalidOperationException("Stdio.s_err not found"), _err);
    }

    private static void SetStatic(FieldInfo f, object value)
    {
        var dm = new System.Reflection.Emit.DynamicMethod("set_" + f.Name, typeof(void), [typeof(object)], f.DeclaringType!.Module, skipVisibility: true);
        var il = dm.GetILGenerator();
        il.Emit(System.Reflection.Emit.OpCodes.Ldarg_0);
        il.Emit(System.Reflection.Emit.OpCodes.Castclass, f.FieldType);
        il.Emit(System.Reflection.Emit.OpCodes.Stsfld, f);
        il.Emit(System.Reflection.Emit.OpCodes.Ret);
        dm.Invoke(null, [value]);
        if (!ReferenceEquals(f.GetValue(null), value))
        {
            throw new InvalidOperationException("could not redirect " + f.Name);
        }
    }

    public ProcResult Run(string[] args, int timeoutMs)
    {
        _argBytes.SetValue(null, args.Select(a => Encoding.UTF8.GetBytes(a)).ToArray());
        _out.Take();
        _err.Take();
        int exit = 0;
        string extraErr = "";
        var sw = Stopwatch.StartNew();
        Exception? fault = null;
        var t = new Thread(() =>
        {
            try
            {
                exit = (int)_entry.Invoke(null, [args])!;
            }
            catch (TargetInvocationException tie) when (tie.InnerException is not null)
            {
                fault = tie.InnerException;
            }
            catch (Exception ex)
            {
                fault = ex;
            }
        }, 64 * 1024 * 1024);
        t.Start();
        if (!t.Join(timeoutMs))
        {
            TimedOut = true;
            return new ProcResult(-1, "", "", true, sw.ElapsedMilliseconds);
        }
        if (fault is not null)
        {
            exit = 101;
            string msg = fault.GetType() == _panicType ? fault.Message : fault switch
            {
                IndexOutOfRangeException => "index out of bounds",
                ArgumentOutOfRangeException => "slice out of bounds",
                DivideByZeroException => "attempt to divide by zero",
                OverflowException => "arithmetic overflow",
                OutOfMemoryException => "out of memory",
                _ => "internal error: " + fault.GetType().Name,
            };
            extraErr = "panic: " + msg + "\n";
            if (fault.GetType() != _panicType)
            {
                LastFault = fault.ToString();
            }
        }
        return new ProcResult(exit, _out.Take(), _err.Take() + extraErr, false, sw.ElapsedMilliseconds);
    }

    /// <summary>Set once a run timed out; the host thread may still be running and the host must be replaced.</summary>
    public bool TimedOut { get; private set; }

    public string? LastFault { get; private set; }
}

/// <summary>Self compiler invocation: in-process host or one `dotnet vib-self.dll` process per call.</summary>
internal sealed class SelfOracle(Toolchain tc, bool inProcess) : IDisposable
{
    private SelfHost? _host = inProcess ? new SelfHost(tc) : null;

    public ProcResult Invoke(params string[] args)
    {
        if (_host is null)
        {
            return Proc.Run("dotnet", [tc.SelfDll, .. args], 60_000);
        }
        var r = _host.Run(args, 60_000);
        if (_host.TimedOut)
        {
            // abandon the stuck host (its thread keeps running); a fresh ALC replaces it
            _host = new SelfHost(tc);
        }
        return r;
    }

    public ProcResult Check(string path) => Invoke("check", path, "--sysroot", tc.Sysroot);

    /// <summary>The real `vib-self build` (its own clang flags and libraries).</summary>
    public ProcResult Build(string path, string binPath, int opt, bool asan) =>
        asan ? Invoke("build", path, "--sysroot", tc.Sysroot, "-O" + opt, "--asan", "-o", binPath) : Invoke("build", path, "--sysroot", tc.Sysroot, "-O" + opt, "-o", binPath);

    public ProcResult EmitLl(string path, string llPath, bool asan) =>
        asan ? Invoke("emit-ll", path, "--sysroot", tc.Sysroot, "--asan", "-o", llPath) : Invoke("emit-ll", path, "--sysroot", tc.Sysroot, "-o", llPath);

    public void Dispose() => _host = null;
}
