    // Cut parity compares the primary diagnostic only: secondary ownership or
    // promoted C# diagnostics are deliberately not part of the cut contract.
    internal static async Task AssertCutRejected(string markedSource, string message, string? expectedWarning = null)
    {
        const string marker = "/*move*/";
        int start = markedSource.IndexOf(marker, StringComparison.Ordinal);
        Assert.True(start >= 0, "A cut rejection must mark its first offending token.");
        string source = markedSource.Replace(marker, "", StringComparison.Ordinal);
        string temp = Path.Combine(Path.GetTempPath(), $"vibranium-r12-cut-reject-{Guid.NewGuid():N}");
        Directory.CreateDirectory(temp);
        try
        {
            string path = Path.Combine(temp, "Program.cs");
            File.WriteAllText(path, source);
            var compilation = VibraniumCompilerDriver.CreateCompilationFromPath(path, "CutRejected", includeStd: true);
            var diagnostics = compilation.GetDiagnostics();
            Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error && d.Id != expectedWarning);
            if (expectedWarning is not null) Assert.Contains(diagnostics, d => d.Id == expectedWarning);
            var frontend = VibraniumFrontend.CompileAndCheck(compilation);
            var cut = Assert.Single(frontend.Diagnostics, d => d.Message == message);
            Assert.Equal(("VIB000", start), (cut.Id, cut.Span.Start));
            var analyzer = await compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new VibraniumDiagnosticAnalyzer())).GetAnalyzerDiagnosticsAsync();
            var analyzerCut = Assert.Single(analyzer, d => d.GetMessage() == message);
            Assert.Equal((cut.Id, cut.Message, cut.Span.Start), (analyzerCut.Id, analyzerCut.GetMessage(), analyzerCut.Location.SourceSpan.Start));
            Assert.False(VibraniumCompilerDriver.CheckAndEmitIr(compilation).Success);
            var self = Run(DotnetExe, SelfCompiler, "check", path, "--sysroot", Path.Combine(RepoRoot, "src"));
            Assert.NotEqual(0, self.Exit);
            Assert.Single(Regex.Matches(self.Out + self.Err, Regex.Escape(message)));
            int line = 1 + source[..start].Count(c => c == '\n');
            int column = start - source.LastIndexOf('\n', start);
            Assert.Contains($"({line},{column}): error VIB000: {message}", self.Out + self.Err, StringComparison.Ordinal);
        }
        finally { Directory.Delete(temp, recursive: true); }
    }

