    [Theory]
    [InlineData("(nint)2147483648L",false)]
    [InlineData("(nint)(2147483648.0)",false)]
    [InlineData("(nuint)(4294967296.0f)",false)]
    [InlineData("(nint)(2147483648.0)",true)]
    public async Task NativeIntegerCutIsCanonicalAndUnsuppressible(string expression,bool suppress)
    {
        string temp=Path.Combine(Path.GetTempPath(),$"vibranium-r11-native-warning-{Guid.NewGuid():N}");Directory.CreateDirectory(temp);
        try
        {
            string source=(suppress?"#pragma warning disable CS8778\n":"")+$"WriteLine({expression});";
            string path=Path.Combine(temp,"Program.cs");File.WriteAllText(path,source);
            var compilation=VibraniumCompilerDriver.CreateCompilationFromPath(path,"NativeWarning",includeStd:true);
            if(suppress)compilation=compilation.WithOptions(compilation.Options.WithSpecificDiagnosticOptions(compilation.Options.SpecificDiagnosticOptions.SetItem("CS8778",ReportDiagnostic.Suppress)));
            var frontend=VibraniumFrontend.CompileAndCheck(compilation);
            var diagnostic=Assert.Single(frontend.Diagnostics,d=>d.Message==Round11AuditAssertions.NativeIntegerMessage);Assert.Equal("VIB000",diagnostic.Id);
            int nativeStart=source.IndexOf(expression.Contains("nuint",StringComparison.Ordinal)?"nuint":"nint",StringComparison.Ordinal);
            Assert.Equal(nativeStart,diagnostic.Span.Start);
            var analyzer=await compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new VibraniumDiagnosticAnalyzer())).GetAnalyzerDiagnosticsAsync();
            var cut=Assert.Single(analyzer,d=>d.GetMessage()==Round11AuditAssertions.NativeIntegerMessage);
            Assert.Equal((diagnostic.Id,diagnostic.Message,diagnostic.Span.Start),(cut.Id,cut.GetMessage(),cut.Location.SourceSpan.Start));
            Assert.False(VibraniumCompilerDriver.CheckAndEmitIr(compilation).Success);
            var self=Round11AuditAssertions.Run(Round11AuditAssertions.DotnetExe,Round11AuditAssertions.SelfCompiler,"check",path,"--sysroot",Path.Combine(Round11AuditAssertions.RepoRoot,"src"));
            Assert.NotEqual(0,self.Exit);Assert.Single(Regex.Matches(self.Out+self.Err,Regex.Escape(Round11AuditAssertions.NativeIntegerMessage)));
            int line=1+source[..nativeStart].Count(c=>c=='\n');int column=nativeStart-source.LastIndexOf('\n',nativeStart);
            Assert.Contains($"({line},{column}): error VIB000: {Round11AuditAssertions.NativeIntegerMessage}",self.Out+self.Err,StringComparison.Ordinal);
        }
        finally{Directory.Delete(temp,recursive:true);}
    }

