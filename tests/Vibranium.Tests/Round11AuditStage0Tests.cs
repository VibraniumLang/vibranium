    [Theory]
    [InlineData("Program.cs", "// <auto-generated/>\n", false)]
    [InlineData("Program.g.cs", "", false)]
    [InlineData("Program.designer.cs", "", false)]
    [InlineData("Program.cs", "", true)]
    public async Task GeneratedMarkersCannotDisableOwnershipAnalysis(string name, string header, bool configuredGenerated)
    {
        string temp=Path.Combine(Path.GetTempPath(), $"vibranium-r11-generated-{Guid.NewGuid():N}");
        Directory.CreateDirectory(temp);
        try
        {
            string source=header+"Vec<int>v=[1];var w=v;WriteLine(v.Count);";
            string path=Path.Combine(temp,name);
            File.WriteAllText(path,source);
            var compilation=VibraniumCompilerDriver.CreateCompilationFromPath(path,"GeneratedOwnership",includeStd:true);
            if(configuredGenerated)
            {
                // Roslyn's options provider is the semantic result of an editorconfig
                // generated_code=true entry, not an analyzer-specific option.
                compilation=compilation.WithOptions(compilation.Options.WithSyntaxTreeOptionsProvider(new GeneratedTrees()));
            }
            var frontend=VibraniumFrontend.CompileAndCheck(compilation);
            Assert.Equal(new[]{"VIB001"},frontend.Diagnostics.Select(d=>d.Id).Distinct());
            var analyzer=await compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new VibraniumDiagnosticAnalyzer())).GetAnalyzerDiagnosticsAsync();
            Assert.Equal(new[]{"VIB001"},analyzer.Select(d=>d.Id).Distinct());
