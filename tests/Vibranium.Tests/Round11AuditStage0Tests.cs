    private const string ConditionalMessage="Conditional compilation directives (#if, #elif, #else, #endif, #define, #undef) are not supported in Vibranium v0.2; .NET and native builds must compile the same code.";
    private const string FileMessage="File-local types (file class, file struct) are not supported in Vibranium v0.2; declare the type without the file modifier.";
    private const string PartialMessage="Partial types and members are not supported in Vibranium v0.2.";
    private const string NestedMessage="Types nested inside a generic type are not supported in Vibranium v0.2; declare the type at namespace level.";
    private const string ChainingMessage="Constructor chaining (: this(...)) is not supported in Vibranium v0.2; initialize every field in each constructor or use a static factory method.";

    [Theory]
    [InlineData("#if true\nclass TYPE{}\n#endif\n",ConditionalMessage)]
    [InlineData("file class TYPE{}",FileMessage)]
    [InlineData("partial class TYPE{}partial class TYPE{}",PartialMessage)]
    [InlineData("class TYPE<T>{public class Inner{}}",NestedMessage)]
    [InlineData("class TYPE{public TYPE():this(0){}public TYPE(int n){}}",ChainingMessage)]
    public async Task CutMultiplicityIsPerKindPerFileAndLeavesTheCleanFileAlone(string template,string message)
    {
        string temp=Path.Combine(Path.GetTempPath(),$"vibranium-r11-cut-files-{Guid.NewGuid():N}");Directory.CreateDirectory(temp);
        try
        {
            File.WriteAllText(Path.Combine(temp,"A.cs"),template.Replace("TYPE","A",StringComparison.Ordinal));
            File.WriteAllText(Path.Combine(temp,"B.cs"),template.Replace("TYPE","B",StringComparison.Ordinal));
            File.WriteAllText(Path.Combine(temp,"Program.cs"),"WriteLine(1);");
            File.WriteAllText(Path.Combine(temp,"vib.manifest"),"unit app\nsource Program.cs\nsource A.cs\nsource B.cs\n");
            var compilation=VibraniumCompilerDriver.CreateCompilationFromPath(temp,"CutFiles",includeStd:true);
            Assert.Empty(compilation.GetDiagnostics().Where(d=>d.Severity>=DiagnosticSeverity.Warning));
            var frontend=VibraniumFrontend.CompileAndCheck(compilation);
            Assert.Equal(2,frontend.Diagnostics.Count);
            Assert.All(frontend.Diagnostics,d=>{Assert.Equal("VIB000",d.Id);Assert.Equal(message,d.Message);});
            Assert.Equal(new[]{"A.cs","B.cs"},frontend.Diagnostics.Select(d=>Path.GetFileName(d.Span.FilePath)).OrderBy(n=>n));
            var analyzer=await compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new VibraniumDiagnosticAnalyzer())).GetAnalyzerDiagnosticsAsync();
            Assert.Equal(frontend.Diagnostics.Select(d=>(Path.GetFileName(d.Span.FilePath),d.Span.Start,d.Message)).OrderBy(d=>d.Item1),analyzer.Select(d=>(Path.GetFileName(d.Location.SourceTree!.FilePath),d.Location.SourceSpan.Start,d.GetMessage())).OrderBy(d=>d.Item1));
            var self=Round11AuditAssertions.Run(Round11AuditAssertions.DotnetExe,Round11AuditAssertions.SelfCompiler,"check",temp,"--sysroot",Path.Combine(Round11AuditAssertions.RepoRoot,"src"));
            Assert.NotEqual(0,self.Exit);Assert.Equal(2,Regex.Matches(self.Out+self.Err,@"VIB\d{3}").Count);
            Assert.Equal(2,Regex.Matches(self.Out+self.Err,Regex.Escape(message)).Count);
            Assert.Contains("A.cs(",self.Out+self.Err,StringComparison.Ordinal);Assert.Contains("B.cs(",self.Out+self.Err,StringComparison.Ordinal);
            Assert.DoesNotContain("Program.cs(",self.Out+self.Err,StringComparison.Ordinal);
        }
        finally{Directory.Delete(temp,recursive:true);}
    }

